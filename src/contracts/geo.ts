/**
 * Географические типы, общие для звонка, карточки и карты.
 *
 * Лежат в contracts, а не рядом с картой: точку одинаково читают хук звонка,
 * стор окна карты и сервис геокодирования, и ни один из них не должен ради
 * этого зависеть от компонента карты.
 */

/** Точка на карте. Порядок полей — как в карточке, сначала широта. */
export interface GeoPoint {
  latitude: number;
  longitude: number;
}

/** Точка вместе с адресом: то, что показывается оператору как место вызова. */
export interface IncidentLocation extends GeoPoint {
  address: string;
}

/**
 * Что карта подставляет в карточку.
 *
 * `revision` растёт с каждой подстановкой: форма применяет каждую ровно один
 * раз, даже если оператор дважды щёлкнул в одну и ту же точку. Адреса может
 * не быть — координаты известны сразу, а адрес приходит после геокодирования.
 *
 * Координаты здесь строки: поля карточки редактируются как текст.
 */
export interface IncidentLocationFill {
  revision: number;
  latitude: string;
  longitude: string;
  addressText?: string;
}
