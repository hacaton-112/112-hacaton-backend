-- Условие `after_fact` снято из словаря раскрытия, и версии сценариев, где оно
-- записано, перестали бы загружаться: разбор jsonb валится на незнакомом типе,
-- а с ним и звонок. Исторические версии нужны разбору проведённых занятий,
-- поэтому правило переписывается в ближайшее по смыслу — вопрос о состоянии.
UPDATE "scenario_facts"
SET "disclosure" = jsonb_build_object(
  'type', 'on_question',
  'keywords', to_jsonb(ARRAY['состояни', 'сознан', 'дышат', 'как они'])
)
WHERE "disclosure" ->> 'type' = 'after_fact';
